export function getAnimal(slug: string) {
  return animals.find((animal) => animal.slug === slug)
}

export function getAnimalById(id: string) {
  return animals.find((animal) => animal.id === id)
}

export function featuredAnimals() {
  return animals.filter((animal) => animal.featured)
}

export function relatedAnimals(animal: Animal, limit = 3) {
  return animals.filter((item) => item.id !== animal.id && item.category === animal.category).slice(0, limit)
}
