export function getAnimal(slug: string) {
  return animals.find((item) => item.slug === slug)
}

export function getAnimalById(id: string) {
  return animals.find((item) => item.id === id)
}

export function featuredAnimals() {
  return animals.filter((item) => item.featured)
}

export function relatedAnimals(item: Animal, limit = 3) {
  return animals.filter((other) => other.id !== item.id && other.category === item.category).slice(0, limit)
}
